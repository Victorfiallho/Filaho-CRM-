export const MESSAGES = { en, pt } as const;
export type Lang = keyof typeof MESSAGES;
export const LANGS: { id: Lang; label: string }[] = [
  { id: "en", label: "English" },
  { id: "pt", label: "Português" }
];

// "{name}" placeholders → values; unknown placeholders are left as-is so a
// missing variable is visible instead of silently blank.
export function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  return format(MESSAGES[lang][key] ?? en[key], vars);
}

// Plural pair lookup: key + ".one" when count === 1, else key + ".other".
export function translatePlural(lang: Lang, key: string, count: number, vars?: Record<string, string | number>): string {
  const k = `${key}.${count === 1 ? "one" : "other"}` as MessageKey;
  return translate(lang, k, { count, ...vars });
}

export function detectLang(stored: string | null, navigatorLang: string | undefined): Lang {
  if (stored === "en" || stored === "pt") return stored;
  return (navigatorLang || "").toLowerCase().startsWith("pt") ? "pt" : "en";
}

// "nav.<module id>" key for a MODULES id (TopNav, page titles).
export const navKey = (id: string) => `nav.${id}` as MessageKey;
